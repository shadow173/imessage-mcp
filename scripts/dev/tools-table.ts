// Builds the Tools table in README.md from tools/list, with every tier on, on mock config. Touches no real data.
// Usage:
//   npx tsx scripts/dev/tools-table.ts           # print the table
//   npx tsx scripts/dev/tools-table.ts --write   # replace the table between the tools-table markers in README.md
//   npx tsx scripts/dev/tools-table.ts --check   # exit 1 if README.md's table is out of date (CI runs this)

import { readFileSync, writeFileSync } from 'node:fs';
import { TIER_SCOPE } from '../../src/auth/scopes.js';
import { loadToolConfig, type Tier } from '../../src/config.js';
import { listTools } from '../../src/mcpHandler.js';
import { TOOL_CATALOG } from '../../src/tools/catalog.js';

const README = new URL('../../README.md', import.meta.url);
const START = /<!-- tools-table:start[^>]*-->\n/;
const END = '<!-- tools-table:end -->';
const MARKER =
  "<!-- tools-table:start (generated by `npx tsx scripts/dev/tools-table.ts --write` from tools/list; don't edit) -->";
/** A first sentence longer than this is cut at its last colon, before the list of details. */
const MAX_SUMMARY = 160;

const HEADINGS: Record<Tier, string> = {
  read: 'Read (always on)',
  send: 'Send',
  org: 'Organize',
  pa: 'Private API (off by default)',
  gpt: 'ChatGPT search and fetch',
};

interface ListedTool {
  name: string;
  description?: string;
  inputSchema: { required?: string[] };
  annotations?: { readOnlyHint?: boolean; destructiveHint?: boolean; openWorldHint?: boolean };
}

/** The description's first sentence without parentheticals or the closing period, safe inside a table cell. */
function summary(description = ''): string {
  let s = description;
  for (let prev = ''; prev !== s; ) {
    prev = s;
    s = s.replace(/\s*\([^()]*\)/g, '');
  }
  let first = (s.match(/^.*?[.!?](?=\s|$)/)?.[0] ?? s)
    .replace(/[.!?]$/, '')
    .replace(/\s+/g, ' ')
    .trim();
  if (first.length > MAX_SUMMARY && first.includes(': ')) first = first.slice(0, first.lastIndexOf(': '));
  return first.replace(/</g, '&lt;').replace(/\|/g, '\\|');
}

function effect(a: ListedTool['annotations'] = {}): string {
  if (a.readOnlyHint) return 'Read-only';
  if (a.openWorldHint) return a.destructiveHint ? 'Can reach others, can delete' : 'Can reach others';
  return a.destructiveHint ? 'Can delete' : 'Saved on the Mac';
}

async function table(): Promise<string> {
  const cfg = loadToolConfig(
    {},
    { timeZone: 'UTC', linkSecret: 'tools-table-link-secret-0123456789', tiers: 'read,send,org,pa,gpt' },
  );
  const { tools } = (await listTools(cfg)) as { tools: ListedTool[] };
  const byName = new Map(tools.map((t) => [t.name, t]));
  const out: string[] = [];
  /** Tools without a required intent: only the ChatGPT contract's, whose arguments are fixed. */
  const optional: string[] = [];
  for (const tier of Object.keys(HEADINGS) as Tier[]) {
    out.push(`### ${HEADINGS[tier]} · \`${tier}\` · \`${TIER_SCOPE[tier]}\``, '');
    out.push('| Tool | What it does | Effect |', '|---|---|---|');
    for (const [name, t] of TOOL_CATALOG) {
      if (t !== tier) continue;
      const tool = byName.get(name);
      if (!tool) throw new Error(`${name} is in TOOL_CATALOG but not in tools/list.`);
      const optionalIntent = !(tool.inputSchema.required ?? []).includes('intent');
      if (optionalIntent) optional.push(`\`${name}\``);
      out.push(
        `| \`${name}\`${optionalIntent ? '¹' : ''} | ${summary(tool.description)} | ${effect(tool.annotations)} |`,
      );
    }
    out.push('');
  }
  if (optional.length) {
    const names = optional.length > 1 ? `${optional.slice(0, -1).join(', ')} and ${optional.at(-1)}` : optional[0];
    out.push(`¹ \`intent\` is optional for ${names}, whose arguments the ChatGPT contract fixes.`, '');
  }
  return out.join('\n');
}

const mode = process.argv[2];
const generated = await table();
if (mode !== '--write' && mode !== '--check') {
  process.stdout.write(generated);
} else {
  const readme = readFileSync(README, 'utf8');
  const start = readme.match(START);
  const end = readme.indexOf(END);
  if (!start || start.index === undefined || end < start.index) {
    console.error('README.md has no tools-table:start / tools-table:end markers.');
    process.exit(1);
  }
  const next = `${readme.slice(0, start.index)}${MARKER}\n\n${generated}\n${readme.slice(end)}`;
  if (mode === '--write') {
    writeFileSync(README, next);
    console.log(
      next === readme ? 'README.md Tools table is already up to date.' : 'Updated the README.md Tools table.',
    );
  } else if (next !== readme) {
    console.error('README.md Tools table is out of date. Run: npx tsx scripts/dev/tools-table.ts --write');
    process.exitCode = 1;
  }
}
